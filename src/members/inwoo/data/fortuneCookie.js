/**
 * 오늘의 한 줄.
 *
 * 날짜를 씨앗으로 골라, 같은 날에는 몇 번을 열어도 같은 말이 나온다.
 * 새로고침할 때마다 바뀌면 "오늘의" 라는 말이 무색해지기 때문이다.
 * 대신 화면의 '하나 더' 버튼은 일부러 무작위로 뽑는다 — 그건 덤이니까.
 */
export const messageOfToday = (date = new Date()) => {
  const key = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate()
  return cookieMessages[key % cookieMessages.length]
}

/** 방금 본 것과는 다른 한 줄 */
export const anotherMessage = (current = '') => {
  const rest = cookieMessages.filter((message) => message !== current)
  return rest[Math.floor(Math.random() * rest.length)]
}
