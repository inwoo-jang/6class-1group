/**
 * 지금 이 화면이 표지 카드 안에서 축소되어 보이는 중인가.
 * ------------------------------------------------------------------
 * 표지는 결과물을 iframe 으로 띄우고 주소 뒤에 ?preview=1 을 붙인다.
 * 그 안에서는 아무도 버튼을 누르지 않고, 아무도 기다려 주지 않는다.
 * 그래서 "불러오는 중" 이나 "연결할 수 없습니다" 같은, 잠깐 스쳐 가라고
 * 만든 화면들이 카드에서는 그대로 굳어 버린다.
 *
 * 카드에 걸려야 하는 것은 그 사람의 결과물이지 결과물을 기다리는 모습이 아니다.
 * 그래서 미리보기에서는 마지막으로 제대로 받아 둔 것을 먼저 보여 준다.
 */
export const isPreview =
  typeof location !== 'undefined' && new URLSearchParams(location.search).has('preview')
